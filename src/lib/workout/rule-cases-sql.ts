import { RULE_CASES } from "./rule-cases";

const quote = (text: string) => `'${text.replace(/'/g, "''")}'`;

/** The pgTAP file for RULE_CASES (see scripts/generate-rule-cases.ts). */
export function ruleCasesSql(): string {
  const checks = RULE_CASES.map((c) => {
    if (c.rule === "result") {
      const v = c.value;
      const sql = (n: number | null, type: string) => (n === null ? `null::${type}` : String(n));
      const call =
        `private.block_result_problem(${quote(c.format)}, ${quote(JSON.stringify(c.params))}::jsonb, ` +
        `${sql(v.rounds_low, "numeric")}, ${sql(v.rounds_high, "numeric")}, ${sql(v.finish_low_s, "int")}, ${sql(v.finish_high_s, "int")})`;
      return `select is(${call} is null, ${c.valid}, ${quote(`result ${c.format}: ${c.why} (${c.valid ? "valid" : "invalid"})`)});`;
    }
    const json = `${quote(JSON.stringify(c.value))}::jsonb`;
    const call =
      c.rule === "params" ? `private.block_params_valid(${quote(c.format)}, ${json})`
      : c.rule === "quantity" ? `private.item_quantity_valid(${json})`
      : c.rule === "load" ? `private.item_load_valid(${json})`
      : c.rule === "guidelines" ? `private.guidelines_problem(${json}) is null`
      : `private.pace_is_valid(${json})`;
    const label = `${c.rule}${c.rule === "params" ? ` ${c.format}` : ""}: ${c.why} (${c.valid ? "valid" : "invalid"})`;
    return `select is(${call}, ${c.valid}, ${quote(label)});`;
  });
  return [
    "-- GENERATED by `npm run rules:generate` from src/lib/workout/rule-cases.ts. Do not edit.",
    "-- The same cases are checked against the app's zod schemas in Vitest, so the",
    "-- builder's instant checks and the database's rules cannot drift apart.",
    "",
    "begin;",
    "create extension if not exists pgtap with schema extensions;",
    "",
    `select plan(${checks.length});`,
    "",
    ...checks,
    "",
    "select * from finish();",
    "rollback;",
    "",
  ].join("\n");
}
