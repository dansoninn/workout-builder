export type Category = keyof typeof CATEGORIES;

type Base = {
  name: string;
  category: Category;
  plane: PlaneKey;
  unit: MeasureUnit;
  unilateral?: boolean;
  equipment?: EquipmentKey[];
  aliases?: string[];
  /** Shown to the reviewer next to the exercise. */
  note?: string;
};

export type MovementExercise = Base & {
  kind: "movement";
  patterns: Partial<Record<PatternKey, number>>;
  primary: MuscleKey[];
  secondary?: MuscleKey[];
};

export type MonostructuralExercise = Base & {
  kind: "monostructural";
  modality: ModalityKey;
};

export type CoreExercise = MovementExercise | MonostructuralExercise;

