import { createHash } from "node:crypto";

import {
  CATEGORIES,
  CORE_EXERCISES,
  type Category,
  type CoreExercise,
} from "@/lib/library/core-exercises";
import { EQUIPMENT } from "@/lib/library/equipment";
import { normalizeAlias } from "@/lib/normalize-alias";
import { PATTERNS, type MuscleKey, type PatternKey } from "@/lib/taxonomy";

export const MIGRATION_PATH = "supabase/migrations/20261021001000_core_exercise_library.sql";
export const REVIEW_DOC_PATH = "docs/review-core-library.md";

// Fixed namespace so core exercise ids are identical in every database.
const CORE_EXERCISE_NAMESPACE = "3c1f0a52-7d4e-4b8a-9f63-5e2b8c7d1a04";

/** RFC 4122 version-5 (name-based, SHA-1) UUID. */
export function uuidV5(name: string, namespace: string): string {
  const hash = createHash("sha1")
    .update(Buffer.from(namespace.replace(/-/g, ""), "hex"))
    .update(name, "utf8")
    .digest()
    .subarray(0, 16);
  hash.writeUInt8((hash.readUInt8(6) & 0x0f) | 0x50, 6);
  hash.writeUInt8((hash.readUInt8(8) & 0x3f) | 0x80, 8);
  const hex = hash.toString("hex");
  return [hex.slice(0, 8), hex.slice(8, 12), hex.slice(12, 16), hex.slice(16, 20), hex.slice(20)].join("-");
}

export function slugify(name: string): string {
  return normalizeAlias(name).replace(/ /g, "-");
}

export function exerciseId(exercise: CoreExercise): string {
  return uuidV5(slugify(exercise.name), CORE_EXERCISE_NAMESPACE);
}

/** Canonical name first, then the listed aliases, normalised and de-duplicated. */
export function aliasesOf(exercise: CoreExercise): string[] {
  return [...new Set([exercise.name, ...(exercise.aliases ?? [])].map(normalizeAlias))];
}

/** Patterns in taxonomy order, as [key, weight] pairs. */
export function patternsOf(exercise: CoreExercise): [PatternKey, number][] {
  if (exercise.kind !== "movement") return [];
  return PATTERNS.flatMap((key): [PatternKey, number][] => {
    const weight = exercise.patterns[key];
    return weight === undefined ? [] : [[key, weight]];
  });
}

export function musclesOf(exercise: CoreExercise): { primary: MuscleKey[]; secondary: MuscleKey[] } {
  if (exercise.kind !== "movement") return { primary: [], secondary: [] };
  return { primary: exercise.primary, secondary: exercise.secondary ?? [] };
}

