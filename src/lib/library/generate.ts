const sql = (value: string | null): string => (value === null ? "null" : `'${value.replace(/'/g, "''")}'`);

function valuesBlock(rows: string[]): string {
  return rows.map((row, i) => (row.startsWith("--") ? `  ${row}` : `  ${row}${i === rows.length - 1 ? ";" : ","}`)).join("\n");
}

/** Rows grouped per exercise, each group headed by a comment with its name. */
function groupedRows(build: (exercise: CoreExercise, id: string) => string[]): string[] {
  const rows: string[] = [];
  for (const exercise of CORE_EXERCISES) {
    const own = build(exercise, exerciseId(exercise));
    if (own.length > 0) rows.push(`-- ${exercise.name}`, ...own);
  }
  return rows;
}

export function buildMigrationSql(): string {
  const aliasCount = CORE_EXERCISES.reduce((n, e) => n + aliasesOf(e).length, 0);

  const exerciseRows = CORE_EXERCISES.map((e) =>
    `(${sql(exerciseId(e))}, null, ${sql(e.name)}, ${sql(slugify(e.name))}, ${sql(e.kind)}, ` +
    `${sql(e.kind === "monostructural" ? e.modality : null)}, ${sql(e.plane)}, ${e.unilateral ? "true" : "false"}, ` +
    `${sql(e.unit)}, 'active')`,
  );

  return `-- Core exercise library and equipment list (Step 2).
--
-- GENERATED by \`npm run library:generate\` from src/lib/library/. Do not edit
-- by hand: change the source, regenerate, and let the tests confirm.
-- ${CORE_EXERCISES.length} exercises, ${EQUIPMENT.length} equipment items, ${aliasCount} core aliases.
-- Equipment belongs to taxonomy version 2 (decided by Daniel 2026-10-21).
-- Exercise ids are UUID v5 of the slug, so they are the same in every database.
-- pace_default is left empty until pace defaults are decided (calc spec §9.5).

insert into public.equipment (key, label_en, position) values
${valuesBlock(EQUIPMENT.map((item, i) => `(${sql(item.key)}, ${sql(item.label)}, ${i + 1})`))}

update public.taxonomy_versions
set notes = ${sql(
    'Removed modality "sled" (sled work is a movement with patterns). Monostructural exercises have no patterns. ' +
      `Added the equipment reference table with ${EQUIPMENT.length} items (Step 2).`,
  )}
where version = 2;

insert into public.exercises (id, org_id, name, slug, kind, modality, plane, unilateral, default_unit, status) values
${valuesBlock(exerciseRows)}

insert into public.exercise_patterns (exercise_id, pattern_key, weight) values
${valuesBlock(groupedRows((e, id) => patternsOf(e).map(([key, weight]) => `(${sql(id)}, ${sql(key)}, ${weight.toFixed(2)})`)))}

insert into public.exercise_muscles (exercise_id, muscle_key, role) values
${valuesBlock(
    groupedRows((e, id) => {
      const { primary, secondary } = musclesOf(e);
      return [
        ...primary.map((m) => `(${sql(id)}, ${sql(m)}, 'primary')`),
        ...secondary.map((m) => `(${sql(id)}, ${sql(m)}, 'secondary')`),
      ];
    }),
  )}

insert into public.exercise_equipment (exercise_id, equipment_key) values
${valuesBlock(groupedRows((e, id) => (e.equipment ?? []).map((key) => `(${sql(id)}, ${sql(key)})`)))}

insert into public.exercise_aliases (org_id, alias_normalized, exercise_id) values
${valuesBlock(groupedRows((e, id) => aliasesOf(e).map((alias) => `(null, ${sql(alias)}, ${sql(id)})`)))}
`;
}

