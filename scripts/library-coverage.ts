// Runs every workout of a programming spreadsheet through the paste parser and
// reports what the exercise library covers (BACKLOG "Exercise library",
// 2026-10-23). The spreadsheet stays on this machine (gyms' documents are
// private); the report holds exercise words and counts only, no workouts.
//
//   npx tsx scripts/library-coverage.ts docs/reference/programming/afrek-2024.xlsx [--report docs/library-coverage.md] [--lines out.txt]
//
// Layout read: one sheet per month, row 1 the program names over their columns,
// one row per day; every other cell with words is one workout.

import { readFileSync, writeFileSync } from "node:fs";

import { readXlsx } from "@/lib/import/xlsx";
import { CORE_EXERCISES } from "@/lib/library/core-exercises";
import { patternsOf } from "@/lib/library/generate";
import { PROPOSED_AMBIGUOUS, PROPOSED_CHANGES, PROPOSED_EXERCISES, UNCLEAR_WORDS } from "@/lib/library/proposed-additions";
import type { Library } from "@/lib/workout/library";
import { PARSER_VERSION, parseWorkoutText, type ParseResult, termOf } from "@/lib/workout/parse";
import { coreLibrary } from "@/lib/workout/test-library";

export interface Cell {
  sheet: string;
  row: number;
  program: string;
  text: string;
}

/** The workout cells: under a program heading in row 1, below it, with words in them. */
export function workoutCells(bytes: Uint8Array): Cell[] {
  const cells: Cell[] = [];
  for (const sheet of readXlsx(bytes).sheets) {
    const headings = (sheet.rows[0] ?? []).map((text, column) => ({ text: text.trim(), column })).filter((h) => h.text);
    sheet.rows.slice(1).forEach((row, r) => {
      row.forEach((text, column) => {
        const heading = [...headings].reverse().find((h) => h.column <= column);
        // A workout has a number somewhere; a cell of words alone is the program's day focus ("Squat", "Bench Press").
        if (!heading || !/[a-z]{2}/i.test(text) || !/\d/.test(text) || /^\?+$/.test(text.trim())) return;
        cells.push({ sheet: sheet.name, row: r + 2, program: heading.text, text });
      });
    });
  }
  return cells;
}

interface Tally {
  workouts: number;
  blocked: number;
  matched: Map<string, number>;
  ambiguous: Map<string, number>;
  unknown: Map<string, number>;
  /** What the words were read as, by the words as written (normalised). */
  readAs: Map<string, string>;
}

const bump = (map: Map<string, number>, key: string) => map.set(key, (map.get(key) ?? 0) + 1);
const total = (map: Map<string, number>) => [...map.values()].reduce((a, b) => a + b, 0);
const ranked = (map: Map<string, number>) => [...map].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

function tally(cells: Cell[], library: Library): Tally {
  const t: Tally = { workouts: cells.length, blocked: 0, matched: new Map(), ambiguous: new Map(), unknown: new Map(), readAs: new Map() };
  for (const cell of cells) {
    const parsed = parseWorkoutText(cell.text, library);
    if (parsed.lines.some((l) => l.blocking)) t.blocked++;
    for (const item of parsed.lines.flatMap((l) => l.items)) {
      const r = item.resolution;
      if (!r) continue;
      if (r.kind === "matched") bump(t.matched, r.exercise.name);
      else if (r.kind === "ambiguous") bump(t.ambiguous, r.term);
      else bump(t.unknown, r.term);
      t.readAs.set(termOf(item.words), r.kind === "matched" ? r.exercise.name : r.kind === "ambiguous" ? "asked" : "unknown");
    }
  }
  return t;
}

const pct = (part: number, whole: number) => `${Math.round((part / whole) * 100)}%`;
const PATTERN_TEXT = (weights: [string, number][]) => (weights.length ? weights.map(([k, w]) => (w === 1 ? k : `${k} ${w}`)).join(", ") : "none");
const paceText = (pace: { secPerRep?: number; secPerM?: number } | null) =>
  pace?.secPerRep ? `${pace.secPerRep} s/rep` : pace?.secPerM ? `${pace.secPerM} s/m` : "by time";

/** docs/library-coverage.md: exercise words and counts only, never a workout. */
function report(now: Tally, proposed: Tally, library: Library): string {
  const mentions = (t: Tally) => total(t.matched) + total(t.ambiguous) + total(t.unknown);
  const all = mentions(now);
  const out: string[] = [];
  const line = (text = "") => out.push(text);
  line("# Exercise library coverage");
  line();
  line("Generated by `scripts/library-coverage.ts` from a year of a gym's real programming (Afrek 2024, one sheet per month,");
  line(`one cell per workout), read by the paste parser (version ${PARSER_VERSION}). The spreadsheet stays on the machine it`);
  line("was run on: this report holds exercise words and counts only, never a workout. One gym's words are one gym's");
  line("style: the proposals below use the names most gyms write, and a gym's own phrasing becomes its own alias on import.");
  line();
  line("**Nothing here is in the library yet.** The proposed exercises, aliases and generic words wait for Daniel's approval");
  line("(BACKLOG \"Exercise library\"); approved ones move into `src/lib/library/core-exercises.ts` with one migration.");
  line();
  line("## Summary");
  line();
  line("| | Today | With the proposals |");
  line("|---|---:|---:|");
  line(`| Workouts read | ${now.workouts} | ${proposed.workouts} |`);
  line(`| Exercise mentions | ${all} | ${mentions(proposed)} |`);
  line(`| Matched to a library exercise | ${total(now.matched)} (${pct(total(now.matched), all)}) | ${total(proposed.matched)} (${pct(total(proposed.matched), mentions(proposed))}) |`);
  line(`| Generic word, asked once ("squat") | ${total(now.ambiguous)} (${pct(total(now.ambiguous), all)}) | ${total(proposed.ambiguous)} (${pct(total(proposed.ambiguous), mentions(proposed))}) |`);
  line(`| Unknown, picked by the coach | ${total(now.unknown)} (${pct(total(now.unknown), all)}) | ${total(proposed.unknown)} (${pct(total(proposed.unknown), mentions(proposed))}) |`);
  line(`| Distinct unknown words | ${now.unknown.size} | ${proposed.unknown.size} |`);
  line(`| Library exercises used | ${now.matched.size} | ${proposed.matched.size} |`);
  line();
  line("With the proposals, some lines that were notes (an unknown word with no amount, as a station) become exercises:");
  line("so the mentions grow.");
  line();
  line("\"Unknown\" includes words that are not exercises at all (\"each\", \"rest\", \"stations\"): what the parser still");
  line("misreads, listed under \"Parser follow-ups\". A coach picks an unknown exercise once per import; an owner can keep");
  line("the answer as the gym's name for it.");
  line();

  const gained = (name: string) => (proposed.matched.get(name) ?? 0) - (now.matched.get(name) ?? 0);
  line(`## Proposed new exercises (${PROPOSED_EXERCISES.length})`);
  line();
  line("Ranked by how often this year's programming names them. Patterns, muscles and paces follow the core library's");
  line("conventions (docs/core-library.md, docs/pace-defaults.md); notes flag what needs a decision.");
  line();
  line("| Exercise | Mentions | Patterns | Plane | Unit | Primary | Secondary | Equipment | Implements | Pace (Hard) | Aliases | Note |");
  line("|---|---:|---|---|---|---|---|---|---:|---|---|---|");
  for (const { exercise: e, pace } of [...PROPOSED_EXERCISES].sort((a, b) => gained(b.exercise.name) - gained(a.exercise.name))) {
    const muscles = e.kind === "movement" ? e : null;
    line(`| ${e.name} | ${gained(e.name)} | ${PATTERN_TEXT(patternsOf(e))} | ${e.plane} | ${e.unit} | ${muscles?.primary.join(", ") ?? ""} | ${muscles?.secondary?.join(", ") ?? ""} | ${(e.equipment ?? []).join(", ") || "bodyweight"} | ${e.implementCount ?? 1}${e.unilateral ? ", one side" : ""} | ${paceText(pace)} | ${(e.aliases ?? []).join("; ")} | ${e.note ?? ""} |`);
  }
  line();
  line(`## Proposed changes to core exercises (${PROPOSED_CHANGES.length})`);
  line();
  line("| Exercise | Mentions gained | New aliases | New equipment | Why |");
  line("|---|---:|---|---|---|");
  for (const c of [...PROPOSED_CHANGES].sort((a, b) => gained(b.exercise) - gained(a.exercise))) {
    line(`| ${c.exercise} | ${gained(c.exercise)} | ${(c.aliases ?? []).join("; ")} | ${(c.equipment ?? []).join(", ")} | ${c.why} |`);
  }
  line();
  line("## Proposed generic words");
  line();
  line("| Word | Mentions | Asked between |");
  line("|---|---:|---|");
  for (const t of PROPOSED_AMBIGUOUS) line(`| ${t.term} | ${proposed.ambiguous.get(t.term) ?? 0} | ${t.candidates.join(", ")} |`);
  line();
  line("## Words to explain (Daniel)");
  line();
  line("Seen often enough to matter; what they are cannot be guessed safely.");
  line();
  line("| Words | Mentions | As written |");
  line("|---|---:|---|");
  for (const w of UNCLEAR_WORDS) {
    const n = ranked(now.unknown).filter(([term]) => term.includes(w.words.replace(/°/, ""))).reduce((a, [, c]) => a + c, 0);
    line(`| ${w.words} | ${n} | ${w.seen} |`);
  }
  line();

  line(`## Matched today (${now.matched.size} exercises)`);
  line();
  line("| Exercise | Mentions | | Exercise | Mentions |");
  line("|---|---:|---|---|---:|");
  const matched = ranked(now.matched);
  const half = Math.ceil(matched.length / 2);
  for (let i = 0; i < half; i++) {
    const [a, b] = [matched[i]!, matched[i + half]];
    line(`| ${a[0]} | ${a[1]} | | ${b?.[0] ?? ""} | ${b?.[1] ?? ""} |`);
  }
  line();
  line("## Generic words asked today");
  line();
  line("| Word | Mentions | Asked between |");
  line("|---|---:|---|");
  const names = new Map(library.exercises.map((e) => [e.id, e.name]));
  for (const [term, n] of ranked(now.ambiguous)) {
    line(`| ${term} | ${n} | ${(library.ambiguous[term] ?? []).map((id) => names.get(id) ?? id).join(", ") || "rowing machine or a strength row, by the amount"} |`);
  }
  line();
  const unknown = ranked(now.unknown);
  const shown = unknown.filter(([, n]) => n >= 3);
  line(`## Unknown today, ranked (${shown.length} words seen 3 times or more)`);
  line();
  line(`${unknown.length} distinct words in ${total(now.unknown)} mentions; ${unknown.filter(([, n]) => n === 1).length} are seen once.`);
  line("The last column is what the same words read as with the proposals.");
  line();
  line("| Words as written | Mentions | With the proposals |");
  line("|---|---:|---|");
  for (const [term, n] of shown) line(`| ${term} | ${n} | ${proposed.readAs.get(term) ?? "unknown"} |`);
  line();
  const still = ranked(proposed.unknown).filter(([, n]) => n >= 2);
  line(`## Still unknown with the proposals (${still.length} words seen twice or more)`);
  line();
  line(still.map(([term, n]) => `${term} (${n})`).join(" · "));
  line();
  line("## Parser follow-ups");
  line();
  line("Words above that are not exercises, and what the parser should read instead (BACKLOG):");
  line();
  line("- \"each\", \"for\", \"a\", \"stations\", \"rest\" alone: words of an instruction line read as a station.");
  line("- \"X vs Y\" / \"X vs. Y\": two stations sharing a slot (\"Ski vs. Assault\", \"Wall sit vs handstand hold\").");
  line("- \"laps\" as an amount (\"2 laps KB farmers carry\"): a gym's lap length.");
  line("- Time each side (\"20/20 sec Pallof hold\") and \"Repeat 4 times through\", \"After each round run …\".");
  line("- Spelling slips (\"sqaut\"): the pick list suggests the right exercise; not added as aliases.");
  line();
  line("Already read since this run started (2026-10-23): a bare \"row\" by its amount (BACKLOG); an implement word before");
  line("an exercise done with it or without free weights (\"KB farmers carry\", \"KB split squat\"), also written after it");
  line("(\"G2OH w plate\"); \"rubber band\" as a band; \"strict\", \"explosive\", \"tempo\", \"slow\", \"controlled\" as how, not which;");
  line("\"Power or Squat Clean\" (shared last words); \"Side Plank L\" (one side, written last).");
  line();
  return out.join("\n");
}

function main() {
  const [path, ...args] = process.argv.slice(2);
  if (!path) throw new Error("Usage: tsx scripts/library-coverage.ts <file.xlsx> [--lines out.txt]");
  const option = (name: string) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
  const library = coreLibrary();
  const cells = workoutCells(readFileSync(path));
  const results: { cell: Cell; parsed: ParseResult }[] = cells.map((cell) => ({ cell, parsed: parseWorkoutText(cell.text, library) }));

  const status: Record<string, number> = {};
  const unmatched = new Map<string, number>();
  const ambiguous = new Map<string, number>();
  const matched = new Map<string, number>();
  const notes = new Map<string, number>();
  const problems = new Map<string, number>();
  for (const { parsed } of results) {
    for (const line of parsed.lines) {
      status[line.status] = (status[line.status] ?? 0) + 1;
      if (line.status === "note") bump(notes, line.text.trim());
      for (const p of line.problems) bump(problems, p.replace(/\d+/g, "N").replace(/"[^"]*"/g, '"…"'));
      for (const item of line.items) {
        const r = item.resolution;
        if (!r) continue;
        if (r.kind === "matched") bump(matched, r.exercise.name);
        else if (r.kind === "ambiguous") bump(ambiguous, r.term);
        else bump(unmatched, r.term);
      }
    }
  }
  const top = (map: Map<string, number>, n = 40) => [...map].sort((a, b) => b[1] - a[1]).slice(0, n);
  console.log(`${cells.length} workouts, ${results.filter((r) => r.parsed.lines.some((l) => l.blocking)).length} blocked by a missing number`);
  console.log("lines:", status);
  console.log(`exercises: ${[...matched.values()].reduce((a, b) => a + b, 0)} matched (${matched.size} names), ${[...ambiguous.values()].reduce((a, b) => a + b, 0)} generic (${ambiguous.size}), ${[...unmatched.values()].reduce((a, b) => a + b, 0)} unknown (${unmatched.size})`);
  console.log("top problems:", top(problems, 25));
  console.log("top unknown:", top(unmatched, 30));
  console.log("top notes:", top(notes, 30));

  const reportPath = option("--report");
  if (reportPath) {
    const withProposals = coreLibrary({}, { exercises: PROPOSED_EXERCISES, changes: PROPOSED_CHANGES, ambiguous: PROPOSED_AMBIGUOUS });
    writeFileSync(reportPath, report(tally(cells, library), tally(cells, withProposals), library));
    console.log(`Report written to ${reportPath} (${CORE_EXERCISES.length} core exercises, ${PROPOSED_EXERCISES.length} proposed)`);
  }

  const linesPath = option("--lines");
  if (linesPath) {
    const out: string[] = [];
    for (const { cell, parsed } of results) {
      out.push(`=== ${cell.sheet} row ${cell.row} · ${cell.program}`);
      for (const line of parsed.lines) {
        if (line.status === "blank") continue;
        const items = line.items.map((i) => `${i.resolution?.kind ?? "-"}:${i.resolution?.kind === "matched" ? i.resolution.exercise.name : i.resolution?.term ?? ""}`).join(", ");
        out.push(`${line.status.padEnd(4)} ${line.blocking ? "!" : " "} ${line.text.trim()}  ⟶ ${line.meaning}${items ? ` [${items}]` : ""}${line.problems.length ? ` {${line.problems.join("; ")}}` : ""}`);
      }
    }
    writeFileSync(linesPath, out.join("\n"));
  }
}

if (process.argv[1]?.endsWith("library-coverage.ts")) main();
